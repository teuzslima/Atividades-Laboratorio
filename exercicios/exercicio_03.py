"""
Exercício 03 - Produção da cooperativa agrícola

Lê a quantidade produzida por dois setores e exibe a produção total
do dia.
"""

setor1 = float(input("Quantidade produzida pelo setor 1 (kg): "))
setor2 = float(input("Quantidade produzida pelo setor 2 (kg): "))

total = setor1 + setor2

print(f"Produção total do dia: {total} kg")
